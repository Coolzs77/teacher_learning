def generate_dynamic_chalkboard(l):
    title = l.get('title', '').strip()
    clean_title = re.sub(r'（.*）', '', title).replace('《','').replace('》','').strip()
    author = l.get('author', '').strip()
    genre = l.get('genre', '')
    slice_title = l.get('goldenSlice', {}).get('sliceTitle', '核心段落研读')
    slice_range = l.get('goldenSlice', {}).get('sliceRange', '重点自然段')
    one_gain = l.get('goldenSlice', {}).get('oneGain', '')
    key_points = l.get('speedPlan', {}).get('keyPoints', '')
    diff = l.get('speedPlan', {}).get('difficulties', '')
    paras = l.get('fullText', {}).get('paragraphs', [])

    # Extract some tough words or keywords from paragraphs for subBoard
    sub_words = []
    for p in paras:
        text_p = p.get('content', '')
        if '【课下重点字词注释】' in text_p:
            parts = [x.strip() for x in text_p.replace('【课下重点字词注释】：', '').split('；') if x.strip()]
            for item in parts[:4]:
                m = re.match(r'^[①②③④⑤⑥⑦⑧⑨⑩]?\s*〔?([^〕]+)〕?\s*(.*)', item)
                if m:
                    word, expl = m.group(1).strip(), m.group(2).strip()
                    if word and expl:
                        sub_words.append(f"{word}：{expl[:10]}")
