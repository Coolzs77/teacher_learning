def clean_chinese_spacing(text):
    for _ in range(3):
        text = re.sub(r'([\u4e00-\u9fa5，。？！；：“”‘’（）《》、])\s+([\u4e00-\u9fa5，。？！；：“”‘’（）《》、])', r'\1\2', text)
    return text

def extract_full_text(pdf_reader, start_pdf_page, end_pdf_page, title):
    paragraphs = []
    current_para = ""
    in_exercises = False

    exercise_lines = []
    note_lines = []

    for p in range(start_pdf_page - 1, min(end_pdf_page, len(pdf_reader.pages))):
        page_text = pdf_reader.pages[p].extract_text() or ''
        lines = page_text.split('\n')
        
        for raw_line in lines:
            line = raw_line.strip()
            if not line:
                continue
            # Remove header/footer noise
            if re.match(r'^\d+$', line):
                continue
            if '义务教育教科书' in line or '人 民 教 育 出 版 社' in line or '~ß  rH' in line:
                continue
            if line in ['阅读', '目 录', '目  录', '第一单元', '第二单元', '第三单元', '第四单元', '第五单元', '第六单元', '活动·探究', '任务一', '任务二', '任务三']:
                continue
            if re.match(r'^[I|V|X]+\s*目\s*录', line):
                continue

            # Note lines
            if re.match(r'^[①②③④⑤⑥⑦⑧⑨⑩]', line) or line.startswith('〔') or line.startswith('a '):
                note_lines.append(clean_chinese_spacing(line))
                continue

            # Check exercise section
            if '思考探究' in line or '积累拓展' in line or '研讨与练习' in line or '阅读提示' in line:
                in_exercises = True
                if current_para:
                    paragraphs.append(clean_chinese_spacing(current_para))
                    current_para = ""
                exercise_lines.append(clean_chinese_spacing(line))
                continue

            if in_exercises:
                exercise_lines.append(clean_chinese_spacing(line))
                continue

            # Regular text line
            if current_para:
                last_char = current_para[-1]
                if last_char in ['。', '！', '？', '”', '…', '：'] and (raw_line.startswith('  ') or raw_line.startswith('\u2003') or raw_line.startswith('\u3000') or len(current_para) > 120):
                    paragraphs.append(clean_chinese_spacing(current_para))
                    current_para = line
                else:
                    current_para += line
            else:
                current_para = line

    if current_para:
        paragraphs.append(clean_chinese_spacing(current_para))

    # Clean empty / tiny lines
    cleaned = [p.strip() for p in paragraphs if len(p.strip()) > 3]

    # If post-reading exercises exist, include as reference paragraph
    if exercise_lines:
        ex_summary = ' '.join(exercise_lines[:8])
        if len(ex_summary) > 20:
            cleaned.append(f"【课后思考探究参考】：{ex_summary[:350]}...")

    # If notes exist, include as reference paragraph
    if note_lines:
        nt_summary = ' ； '.join(note_lines[:6])
        if len(nt_summary) > 10:
            cleaned.append(f"【课下重点字词注释】：{nt_summary}")

    return cleaned

